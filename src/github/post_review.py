
import argparse
import json
import os
import sys
from pathlib import Path

import requests
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[2]
ARTIFACTS = ROOT / "artifacts"

load_dotenv(ROOT / ".env")

API_URL = "https://api.github.com"


def load_json(path):
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")

    with open(path, "r", encoding="utf-8") as file:
        return json.load(file)


def normalize_parsed_data(data):
    """
    Support both:
    1. A list of file objects.
    2. A dictionary containing a 'files' list.
    """
    if isinstance(data, list):
        return data

    if isinstance(data, dict):
        files = data.get("files", [])

        if isinstance(files, list):
            return files

    raise ValueError("Unexpected structure in parsed diff JSON.")


def get_added_lines(parsed_data):
    valid_lines = set()

    files = normalize_parsed_data(parsed_data)

    for file_data in files:
        if not isinstance(file_data, dict):
            continue

        filename = file_data.get("filename")

        added_lines = file_data.get("added_lines", [])

        if not isinstance(added_lines, list):
            continue

        for line in added_lines:
            if not isinstance(line, dict):
                continue

            line_number = line.get("line_number")

            if filename and isinstance(line_number, int):
                valid_lines.add((filename, line_number))

    return valid_lines


def build_comment(finding):
    title = finding.get("title", "Code issue")
    severity = finding.get("severity", "LOW")
    explanation = finding.get("explanation", "No explanation provided.")
    suggested_fix = finding.get("suggested_fix", "No suggested fix provided.")

    try:
        confidence = float(finding.get("confidence", 0))
    except (TypeError, ValueError):
        confidence = 0

    confidence = max(0.0, min(1.0, confidence))
    agents = ", ".join(finding.get("agents", []))

    return (
        f"**{severity}: {title}**\n\n"
        f"**Explanation:** {explanation}\n\n"
        f"**Suggested fix:** {suggested_fix}\n\n"
        f"**Confidence:** {confidence:.0%}\n\n"
        f"**Detected by:** {agents or 'AI Review Agent'}"
    )


def build_review_summary(report):
    return (
        "## AI Pull Request Review\n\n"
        f"- **Risk level:** {report.get('risk_level', 'UNKNOWN')}\n"
        f"- **Risk score:** {report.get('risk_score', 0)}/100\n"
        f"- **Unique findings:** {report.get('total_findings', 0)}\n\n"
        "The review findings are attached as inline comments "
        "to the changed lines. Please inspect them before merging.\n\n"
        "_Generated by PR Review Bot._"
    )


def main():
    parser = argparse.ArgumentParser(
        description="Preview or post AI review comments on a GitHub PR."
    )

    parser.add_argument("owner", help="GitHub repository owner")
    parser.add_argument("repo", help="GitHub repository name")
    parser.add_argument("pr_number", type=int, help="Pull Request number")

    parser.add_argument(
        "--post",
        action="store_true",
        help="Actually submit the review to GitHub"
    )

    args = parser.parse_args()

    report_path = ARTIFACTS / f"pr_{args.pr_number}_review_report.json"
    parsed_path = ARTIFACTS / f"pr_{args.pr_number}_parsed.json"

    try:
        report = load_json(report_path)
        parsed_data = load_json(parsed_path)

        if not isinstance(report, dict):
            raise ValueError("Review report must be a JSON object.")

        findings = report.get("findings", [])

        if not isinstance(findings, list):
            raise ValueError("Review report findings must be a list.")

        valid_lines = get_added_lines(parsed_data)

    except (FileNotFoundError, json.JSONDecodeError, ValueError) as error:
        print(f"ERROR: {error}")
        sys.exit(1)

    comments = []
    skipped = []

    for finding in findings:
        if not isinstance(finding, dict):
            continue

        filename = finding.get("filename")
        line_number = finding.get("line_number")

        if (filename, line_number) not in valid_lines:
            skipped.append(f"{filename}:{line_number}")
            continue

        comments.append({
            "path": filename,
            "line": line_number,
            "side": "RIGHT",
            "body": build_comment(finding)
        })

    print("\nGITHUB PULL REQUEST REVIEW")
    print("--------------------------")
    print(f"Repository: {args.owner}/{args.repo}")
    print(f"Pull Request: #{args.pr_number}")
    print(
        f"Risk: {report.get('risk_level')} "
        f"({report.get('risk_score')}/100)"
    )
    print(f"Total findings: {len(findings)}")
    print(f"Valid inline comments: {len(comments)}")
    print(f"Skipped invalid line locations: {len(skipped)}")

    for index, comment in enumerate(comments, start=1):
        print(
            f"\nComment {index}: "
            f"{comment['path']}:{comment['line']}"
        )
        print(comment["body"])

    if skipped:
        print("\nSkipped locations:")
        for location in skipped:
            print(f"- {location}")

    if not comments:
        print("\nNo valid inline comments to submit.")
        return

    if not args.post:
        print("\nDRY RUN completed.")
        print("Nothing has been posted to GitHub.")
        print("Review the preview before using --post.")
        return

    token = os.getenv("GITHUB_TOKEN")

    if not token:
        print("\nERROR: GITHUB_TOKEN is missing from your .env file.")
        sys.exit(1)

    url = (
        f"{API_URL}/repos/{args.owner}/{args.repo}"
        f"/pulls/{args.pr_number}/reviews"
    )

    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28"
    }

    payload = {
        "body": build_review_summary(report),
        "event": "COMMENT",
        "comments": comments
    }

    print("\nSubmitting review to GitHub...")

    try:
        response = requests.post(
            url,
            headers=headers,
            json=payload,
            timeout=30
        )
    except requests.RequestException as error:
        print(f"Network error: {error}")
        sys.exit(1)

    if response.status_code == 200:
        result = response.json()

        print("\nSUCCESS! Review posted to GitHub.")
        print(f"Review ID: {result.get('id')}")
        print(f"Review state: {result.get('state')}")
        print(f"URL: {result.get('html_url')}")

    else:
        print(f"\nGitHub API error: {response.status_code}")

        try:
            print(response.json().get("message", response.text))
        except ValueError:
            print(response.text)

        if response.status_code in (403, 404, 422):
            print(
                "\nCheck token permissions, repository access, "
                "PR status, and whether the comment lines are valid."
            )


if __name__ == "__main__":
    main()

